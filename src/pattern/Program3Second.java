package pattern;

public class Program3Second {
    public  static void main(String[]args){

        for(int i=1;i<=7;i++) {
            String p="";
            for(int j=1;j<=6;j++){
                p=p+"* ";
            }
            System.out.println(p);
        }
    }
}
